        _container = container;
    }

    protected override async Task RunAdditionalTestsAsync()
    {
        await TestAutoGeneratedIdAsync();
        await TestUniqueConstraintExceptionTypeAsync();
        await TestMergeParameterBindingAsync();
    }

    /// <summary>
    /// Db2 LUW's implicit-activation lifecycle deactivates a database as soon as its last
    /// application connection disconnects. This probe measures that cost and whether a real
    /// PreventDatabaseUnload context's sentinel prevents it, against a dedicated database nothing
    /// else connects to (<see cref="Db2TestContainer.EnsureIdleProbeDatabaseAsync"/>):
    /// <list type="bullet">
    /// <item>It does NOT clear the shared pool: <c>DB2Connection.ReleaseObjectPool()</c>, the IBM
    /// driver's only pool-clearing API, was CONFIRMED (standalone repro, Net.IBM.Data.Db2-lnx
    /// 8.0.0.500) to crash the driver under later concurrent use (segfault, or
    /// ArgumentNullException from DB2ConnPool.ReplaceConnStrPwd in the next concurrency test).</item>
    /// <item>Timed samples use raw, unpooled DB2Connections, so no pooled connection keeps the
    /// probe database active. pengdows.crud itself rejects Pooling=false, which is why the samples
    /// are raw; only the pinned phase's PreventDatabaseUnload context goes through pengdows.</item>
    /// <item>Unpinned samples run before the pinned phase (not interleaved): once a pengdows
    /// context has pooled connections to the probe database, it stays active.</item>
    /// </list>
    /// </summary>
    protected override async Task TestIdleUnloadProbe()
    {
        if (_container is null)
        {
            Console.WriteLine("  [DbMode] Idle-unload probe for Db2: no container handle - not measured");
            return;
        }

        const int rounds = 5;
        var probeConnectionString = await _container.EnsureIdleProbeDatabaseAsync();
        var rawUnpooled = probeConnectionString + "Pooling=false;";

        var unpinned = new List<double>(rounds);
        for (var i = 0; i < rounds; i++)
        {
            unpinned.Add(await MeasureColdRawRoundTripAsync(rawUnpooled));
        }

        var pinned = new List<double>(rounds);
        await using (var preventUnload = new DatabaseContext(new DatabaseContextConfiguration
                     {
                         ConnectionString = probeConnectionString,
                         DbMode = DbMode.PreventDatabaseUnload
                     }, DB2Factory.Instance))
        {
            if (preventUnload.ConnectionMode != DbMode.PreventDatabaseUnload)
            {
                throw new InvalidOperationException(
                    $"DbMode.SentinelPreventsUnload: requested PreventDatabaseUnload resolved to {preventUnload.ConnectionMode}.");
            }

            for (var i = 0; i < rounds; i++)
            {
                pinned.Add(await MeasureColdRawRoundTripAsync(rawUnpooled));
            }

            var sentinels = preventUnload.GetSentinelSnapshot();
            if (sentinels.Count == 0 || sentinels.Any(s => s.Connection.State != ConnectionState.Open))
            {
                throw new InvalidOperationException(
                    "DbMode.SentinelPreventsUnload: expected every sentinel Open after the idle windows, got [" +
                    string.Join(", ", sentinels.Select(s => $"{s.ExecutionType}:{s.Connection.State}")) + "].");
            }
        }

        var unpinnedMedian = Median(unpinned);
        var pinnedMedian = Median(pinned);
        var saved = unpinnedMedian - pinnedMedian;
        var detected = saved > Math.Max(3.0, unpinnedMedian * 0.15);
        CheckOk(
            $"  [DbMode] Idle-unload probe for Db2 (dedicated probe database): cold median without sentinel=" +
            $"{unpinnedMedian:F2}ms, with PreventDatabaseUnload sentinel={pinnedMedian:F2}ms (saved {saved:F2}ms; samples: " +
            string.Join("/", unpinned.Select(v => v.ToString("F1"))) + " vs " +
            string.Join("/", pinned.Select(v => v.ToString("F1"))) + ") — " +
            (detected
                ? "unload cost PREVENTED by the sentinel"
                : "no unload cost distinguishable from reconnect cost; sentinels verified Open"));
    }

    private static async Task<double> MeasureColdRawRoundTripAsync(string unpooledConnectionString)
    {
        await Task.Delay(TimeSpan.FromSeconds(3));
        var sw = System.Diagnostics.Stopwatch.StartNew();
        await using (var connection = new DB2Connection(unpooledConnectionString))
        {
            await connection.OpenAsync();
            await using var command = connection.CreateCommand();
            command.CommandText = "SELECT 1 FROM SYSIBM.SYSDUMMY1";
            await command.ExecuteScalarAsync();
        }

        sw.Stop();
        return sw.Elapsed.TotalMilliseconds;
    }

    private static double Median(List<double> values)
    {
        var sorted = values.OrderBy(v => v).ToList();
        var mid = sorted.Count / 2;
        return sorted.Count % 2 == 1 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2.0;
    }

    private async Task TestMergeParameterBindingAsync()
    {
        var tableName = _context.WrapObjectName("db2_merge_parameter_test");
        await using var sc = _context.CreateSqlContainer();

        sc.Query.Append($"DROP TABLE IF EXISTS {tableName}");
        try
        {
            await sc.ExecuteNonQueryAsync();
        }
        catch
        {
            // The table is absent on the first run.
        }

        try
        {
            sc.Clear();
            sc.Query.Append($"CREATE TABLE {tableName} (");
            sc.Query.Append($"{_context.WrapObjectName("id")} INTEGER NOT NULL PRIMARY KEY, ");
            sc.Query.Append($"{_context.WrapObjectName("name")} VARCHAR(100) NOT NULL, ");
            sc.Query.Append($"{_context.WrapObjectName("amount")} DECIMAL(10,2) NOT NULL)");
            await sc.ExecuteNonQueryAsync();

            var gateway = new TableGateway<Db2MergeParameterTestTable, int>(_context);
            var entity = new Db2MergeParameterTestTable { Id = 1, Name = "before", Amount = 12.34m };
            await gateway.UpsertAsync(entity);
            entity.Name = "after";
            entity.Amount = 56.78m;
            await gateway.UpsertAsync(entity);

            var loaded = await gateway.RetrieveOneAsync(1);
            if (loaded?.Name != "after" || loaded.Amount != 56.78m)
            {
                throw new Exception("Db2 MERGE parameter binding did not preserve the updated values");
            }

            CheckOk("Db2 MERGE parameter binding: typed integer, string, and decimal values: OK");
        }
        finally
        {
            sc.Clear();
            sc.Query.Append($"DROP TABLE IF EXISTS {tableName}");
            try
            {
                await sc.ExecuteNonQueryAsync();
            }
            catch
            {
                // Best-effort cleanup.
            }
        }
    }

    /// <summary>
    /// Validates that a real Db2 unique-constraint violation (SQLSTATE 23505) translates to
    /// the SPECIFIC UniqueConstraintViolationException type, not just any DatabaseException.
    /// The base TestErrorMapping() only checks for the generic DatabaseException base class —
    /// this verifies that Db2ExceptionTranslator's SQLSTATE-primary classification actually
    /// fires correctly against the real driver.
    /// </summary>
    private async Task TestUniqueConstraintExceptionTypeAsync()
    {
        Console.WriteLine("Running Db2 unique-constraint exception type check");

        var tableName = _context.WrapObjectName("db2_unique_test_table");

        await using var sc = _context.CreateSqlContainer();
        sc.Query.Append($"DROP TABLE IF EXISTS {tableName}");
        try
        {
            await sc.ExecuteNonQueryAsync();
        }
        catch
        {
            // Table did not exist, ignore.
        }

        try
        {
            sc.Clear();
            sc.Query.Append($@"
CREATE TABLE {tableName} (
    {_context.WrapObjectName("id")} BIGINT NOT NULL PRIMARY KEY,
    {_context.WrapObjectName("name")} VARCHAR(100) NOT NULL
)");
            await sc.ExecuteNonQueryAsync();

            var gateway = new TableGateway<Db2UniqueTestTable, long>(_context);
            var entity = new Db2UniqueTestTable { Id = 1, Name = "first" };
            var ok = await gateway.CreateAsync(entity);
            if (!ok)
            {
                throw new Exception("Db2 unique-constraint check: initial CreateAsync returned false");
            }

            var duplicate = new Db2UniqueTestTable { Id = 1, Name = "duplicate" };
            try
            {
                await gateway.CreateAsync(duplicate);
                throw new Exception(
                    "Db2 unique-constraint check: expected UniqueConstraintViolationException, none thrown");
            }
            catch (UniqueConstraintViolationException ex)
            {
                CheckOk($"Db2 unique-constraint check: correctly threw UniqueConstraintViolationException ({ex.Message[..Math.Min(80, ex.Message.Length)]}...)");
            }
        }
        finally
        {
            sc.Clear();
            sc.Query.Append($"DROP TABLE IF EXISTS {tableName}");
            try
            {
                await sc.ExecuteNonQueryAsync();
            }
            catch
            {
                // best-effort cleanup
            }
        }
    }

    [Table("db2_unique_test_table")]
    private class Db2UniqueTestTable
    {
        [Id]
        [Column("id", System.Data.DbType.Int64)]
        public long Id { get; set; }

        [Column("name", System.Data.DbType.String)]
        public string Name { get; set; } = string.Empty;
    }

    /// <summary>
    /// Validates Db2's generated-key retrieval strategy: SELECT ... FROM FINAL TABLE (INSERT ...).
    /// This cannot be verified against fakeDb alone — it depends on the real Db2 engine actually
    /// accepting this exact wrapped-statement syntax.
    /// </summary>
    private async Task TestAutoGeneratedIdAsync()
    {
        Console.WriteLine("Running Db2 FINAL TABLE clause (auto-generated identity)");

        var tableName = _context.WrapObjectName("db2_auto_id_table");

        await using var sc = _context.CreateSqlContainer();

        sc.Query.Append($"DROP TABLE IF EXISTS {tableName}");
        try
        {
            await sc.ExecuteNonQueryAsync();
        }
        catch
        {
            // Table did not exist, ignore.
        }

        try
        {
            sc.Clear();
            sc.Query.Append($@"
CREATE TABLE {tableName} (
    {_context.WrapObjectName("id")} BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    {_context.WrapObjectName("name")} VARCHAR(100) NOT NULL
)");
            await sc.ExecuteNonQueryAsync();

            var gateway = new TableGateway<Db2AutoIdTable, long>(_context);
            var entity = new Db2AutoIdTable { Name = "final-table-test" };
            var ok = await gateway.CreateAsync(entity);

            if (!ok)
            {
                throw new Exception("Db2 FINAL TABLE: CreateAsync returned false");
            }

            if (entity.Id == 0)
            {
                throw new Exception(
                    "Db2 FINAL TABLE clause did not populate Id — SELECT ... FROM FINAL TABLE (INSERT ...) returned 0 or null");
            }

            CheckOk($"Db2 FINAL TABLE: CreateAsync populated Id = {entity.Id} via SELECT ... FROM FINAL TABLE (INSERT ...)");

            var retrieved = await gateway.RetrieveOneAsync(entity.Id);
            if (retrieved == null || retrieved.Id != entity.Id)
            {
                throw new Exception(
                    $"Db2 FINAL TABLE: RetrieveOneAsync by returned Id {entity.Id} did not find the row");
            }

            CheckOk($"Db2 FINAL TABLE: RetrieveOneAsync confirmed row exists with Id = {retrieved.Id}");
        }
        finally
        {
            sc.Clear();
            sc.Query.Append($"DROP TABLE IF EXISTS {tableName}");
            try
            {
                await sc.ExecuteNonQueryAsync();
            }
            catch
            {
                // best-effort cleanup
            }
        }
    }

    [Table("db2_auto_id_table")]
    private class Db2AutoIdTable
    {
        [Id(false)]
        [Column("id", System.Data.DbType.Int64)]
        public long Id { get; set; }

        [Column("name", System.Data.DbType.String)]
        public string Name { get; set; } = string.Empty;
    }

    [Table("db2_merge_parameter_test")]
    private class Db2MergeParameterTestTable
    {
        [Id]
        [Column("id", System.Data.DbType.Int32)]
        public int Id { get; set; }

        [Column("name", System.Data.DbType.String)]
        public string Name { get; set; } = string.Empty;

        [Column("amount", System.Data.DbType.Decimal)]
        public decimal Amount { get; set; }
    }
}
