// =============================================================================
// FILE: DatabaseTypeCatalog.cs
// PURPOSE: Per-database column-type descriptors for datatype discovery/compatibility testing.
//
// AI SUMMARY:
// - Scope, per the request that produced this file: types that can matter to a DAL as column
//   declarations or returned column metadata. Deliberately excludes: plain ANSI aliases already
//   folded into a canonical entry's Aliases list; internal/query-only expression types with no
//   column-storage meaning; and open-ended user-defined-type escape hatches (Db2 DISTINCT/
//   structured types, Informix DataBlade opaque/distinct types) — those are flagged via
//   IsUserDefined = true on a single catalog-all entry per engine rather than enumerated, because
//   they have no finite list (installed extensions and end users can add more at any time).
// - Deliberately NOT wired into testbed/TestProvider.cs's existing GetIntType/GetLongType/
//   GetBooleanType/GetDateTimeType/GetTextType/GetDecimalType/GetBinaryType/GetGuidType/
//   GetDateTimeOffsetType helpers (see CLAUDE.md item 26 for why those are test-only, and item 19
//   for their production-code-equivalent, IntegrationObjectNameHelper) — this is new, additive
//   reference/discovery infrastructure, not a replacement. Migrating those call sites to consume
//   this catalog is a real, separate follow-up, not attempted here: those helpers are working,
//   tested code with their own live-verified quirks (e.g. InterBaseDialectTests.cs,
//   docs/supported-databases.md), and a blind swap risks silently reintroducing a bug one of those
//   helpers already has a documented fix for.
// - Populated only for the databases with sourced, cited data as of this writing: Db2 LUW 11.5.x,
//   SingleStore, Sybase ASE 16.x, Google Cloud Spanner (PostgreSQL dialect only — pengdows.crud
//   has no GoogleSQL-dialect Spanner support, so that type list is intentionally not modeled
//   here), Informix 14.10, SAP HANA (Cloud QRC 2/2026, with the platform/legacy addendum), and
//   InterBase 15. Every other pengdows.crud-supported database (SQL Server, PostgreSQL, MySQL,
//   MariaDB, Oracle, SQLite, DuckDB, Firebird, CockroachDB, YugabyteDB, TiDB, Snowflake, Aurora
//   MySQL, Aurora PostgreSQL) is deliberately left unpopulated rather than guessed — extend this
//   catalog with the same sourcing discipline (a citable reference or a live-verified fact) when
//   one of those is needed, not by assumption from a "similar" engine.
// - Two real cases prove a flat name -> DbType dictionary is insufficient, which is why this
//   carries structured flags instead: Sybase ASE's predefined `timestamp` UDT LOOKS temporal but
//   is an automatically maintained binary row-version value, not a date/time value at all
//   (IsTemporal = false here, deliberately, despite the name) — and Spanner PostgreSQL's
//   `interval` really is temporal but CanDeclareColumn = false (query-only, cannot be stored in a
//   table column).
// =============================================================================

using pengdows.crud.enums;

