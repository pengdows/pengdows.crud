        SupportedDatabase.Spanner => SpannerPostgreSqlTypes,
        SupportedDatabase.Informix => InformixTypes,
        SupportedDatabase.SapHana => HanaTypes,
        SupportedDatabase.InterBase => InterBaseTypes,
        _ => Array.Empty<ColumnTypeDescriptor>()
    };

