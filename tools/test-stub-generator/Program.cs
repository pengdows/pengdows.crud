using System.Reflection;
using System.Text;

// usage: stubgen <assemblyPath> <interfaceFullName> <className> <outFile> [skipMember,...]
var asm = Assembly.LoadFrom(args[0]);
var iface = asm.GetType(args[1]) ?? throw new Exception("no type " + args[1]);
var className = args[2];
var skip = args.Length > 4 ? args[4].Split(',', StringSplitOptions.RemoveEmptyEntries).ToHashSet() : new HashSet<string>();

string TypeName(Type t)
{
    if (t.IsGenericParameter) return t.Name;
    if (t == typeof(void)) return "void";
    if (t.IsByRef) return TypeName(t.GetElementType()!);
    if (t.IsArray) return TypeName(t.GetElementType()!) + "[" + new string(',', t.GetArrayRank() - 1) + "]";
    var nullable = Nullable.GetUnderlyingType(t);
    if (nullable != null) return TypeName(nullable) + "?";
    var keywords = new Dictionary<Type, string>
    {
        [typeof(int)] = "int", [typeof(long)] = "long", [typeof(string)] = "string", [typeof(bool)] = "bool", [typeof(object)] = "object",
        [typeof(byte)] = "byte", [typeof(short)] = "short", [typeof(double)] = "double", [typeof(float)] = "float", [typeof(decimal)] = "decimal", [typeof(char)] = "char"
    };
    if (keywords.TryGetValue(t, out var k)) return k;
    var name = (t.IsNested ? TypeName(t.DeclaringType!) + "." : (string.IsNullOrEmpty(t.Namespace) ? "" : "global::" + t.Namespace + ".")) + t.Name;
    if (t.IsGenericType)
    {
        var tick = name.IndexOf('`');
        if (tick >= 0) name = name[..tick];
        name += "<" + string.Join(", ", t.GetGenericArguments().Select(TypeName)) + ">";
    }
    return name;
}

var allInterfaces = new List<Type> { iface };
allInterfaces.AddRange(iface.GetInterfaces());
var sb = new StringBuilder();
sb.AppendLine("// <auto-generated>");
sb.AppendLine($"// Generated from {iface.FullName} by a reflection tool: every member throws until a test scripts it.");
sb.AppendLine("// Hand-written partial classes script the members a test needs; they are listed in the skip set at generation time.");
sb.AppendLine("// </auto-generated>");
sb.AppendLine("#nullable disable");
sb.AppendLine("#pragma warning disable CS0108, CS0114, CS8600, CS8601, CS8603, CS8604, CS8767");
sb.AppendLine("using System;");
sb.AppendLine();
sb.AppendLine("namespace pengdows.crud.Tests;");
sb.AppendLine();
var classGenerics = iface.IsGenericTypeDefinition
    ? "<" + string.Join(", ", iface.GetGenericArguments().Select(a => a.Name)) + ">"
    : "";
var constraints = new StringBuilder();
if (iface.IsGenericTypeDefinition)
{
    foreach (var arg in iface.GetGenericArguments())
    {
        var parts = new List<string>();
        var attrs = arg.GenericParameterAttributes;
        if ((attrs & GenericParameterAttributes.ReferenceTypeConstraint) != 0) parts.Add("class");
        if ((attrs & GenericParameterAttributes.NotNullableValueTypeConstraint) != 0) parts.Add("struct");
        parts.AddRange(arg.GetGenericParameterConstraints().Where(c => c != typeof(ValueType)).Select(TypeName));
        if ((attrs & GenericParameterAttributes.DefaultConstructorConstraint) != 0 &&
            (attrs & GenericParameterAttributes.NotNullableValueTypeConstraint) == 0) parts.Add("new()");
        if (parts.Count > 0) constraints.Append($" where {arg.Name} : {string.Join(", ", parts)}");
    }
}
sb.AppendLine($"internal partial class {className}{classGenerics} : {TypeName(iface)}{constraints}");
sb.AppendLine("{");
sb.AppendLine($"    private static NotSupportedException Unscripted(string member) => new($\"{className} does not script {{member}}.\");");
sb.AppendLine();
var emitted = new HashSet<string>();
foreach (var t in allInterfaces)
{
    foreach (var m in t.GetMembers(BindingFlags.Public | BindingFlags.Instance))
    {
        if (m is MethodInfo mi && !mi.IsSpecialName)
        {
            if (!mi.IsAbstract) continue; // default interface members keep their default body
            if (skip.Contains(mi.Name)) continue;
            var ps = string.Join(", ", mi.GetParameters().Select(p =>
                (p.IsOut ? "out " : p.ParameterType.IsByRef ? (p.IsIn ? "in " : "ref ") : "") + TypeName(p.ParameterType) + " " + p.Name));
            var gen = mi.IsGenericMethodDefinition ? "<" + string.Join(", ", mi.GetGenericArguments().Select(a => a.Name)) + ">" : "";
            var sig = $"{TypeName(mi.ReturnType)} {TypeName(t)}.{mi.Name}{gen}({ps})";
            if (!emitted.Add(sig)) continue;
            sb.AppendLine($"    {sig} => throw Unscripted(\"{mi.Name}\");");
        }
        else if (m is PropertyInfo pi)
        {
            var getter = pi.GetMethod; var setter = pi.SetMethod;
            if ((getter?.IsAbstract ?? false) is false && (setter?.IsAbstract ?? false) is false) continue;
            if (skip.Contains(pi.Name)) continue;
            var idx = pi.GetIndexParameters();
            var name = idx.Length > 0 ? "this[" + string.Join(", ", idx.Select(p => TypeName(p.ParameterType) + " " + p.Name)) + "]" : pi.Name;
            var sig = $"{TypeName(pi.PropertyType)} {TypeName(t)}.{name}";
            if (!emitted.Add(sig)) continue;
            var accessors = new List<string>();
            if (getter != null && getter.IsAbstract) accessors.Add($"get => throw Unscripted(\"{pi.Name}\");");
            if (setter != null && setter.IsAbstract) accessors.Add($"set => throw Unscripted(\"{pi.Name}\");");
            sb.AppendLine($"    {sig} {{ {string.Join(" ", accessors)} }}");
        }
        else if (m is EventInfo ei)
        {
            var sig = $"{TypeName(ei.EventHandlerType!)} {TypeName(t)}.{ei.Name}";
            if (!emitted.Add("event " + sig) || skip.Contains(ei.Name)) continue;
            sb.AppendLine($"    event {TypeName(ei.EventHandlerType!)} {TypeName(t)}.{ei.Name} {{ add => throw Unscripted(\"{ei.Name}\"); remove => throw Unscripted(\"{ei.Name}\"); }}");
        }
    }
}
sb.AppendLine("}");
File.WriteAllText(args[3], sb.ToString());
Console.WriteLine($"{className}: {emitted.Count} members -> {args[3]}");
