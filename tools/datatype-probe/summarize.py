#!/usr/bin/env python3
# Joins live probe results (results/*.jsonl) to the workbook's documented status
# (db_xref.txt, SQL mappings sheet) and writes a cross-reference with disagreements.
import collections, glob, json, os, sys

S = os.path.dirname(os.path.abspath(__file__))

# workbook column name -> probe database name
WB_TO_PROBE = {
    'PostgreSQL': 'PostgreSql', 'SQL Server': 'SqlServer', 'Oracle': 'Oracle',
    'Firebird': 'Firebird', 'CockroachDB': 'CockroachDb', 'MariaDB': 'MariaDb',
    'MySQL': 'MySql', 'SQLite': 'Sqlite', 'DuckDB': 'DuckDB', 'YugabyteDB': 'YugabyteDb',
    'TiDB': 'TiDb', 'SingleStore': 'SingleStore', 'Sybase ASE': 'SybaseASE',
    'Spanner PG': 'Spanner', 'pengdows.flatfile': 'FlatFile',
}

# workbook status per (semantic type, probe db)
wb = {}
on = False
for line in open(os.path.join(S, 'db_xref.txt'), encoding='utf-8'):
    if line.startswith('=== SHEET'):
        on = 'SQL mappings' in line
        continue
    if on and '|' in line:
        p = [x.strip() for x in line.rstrip('\n').split(' | ')]
        if len(p) >= 5 and p[0] != 'Category' and p[2] in WB_TO_PROBE:
            wb[(p[1], WB_TO_PROBE[p[2]])] = (p[3], p[4])

# probe results
probe = collections.defaultdict(list)  # (type, db) -> records
dbs_seen = []
container_errors = {}
for path in sorted(glob.glob(os.path.join(S, 'results', '*.jsonl'))):
    for line in open(path, encoding='utf-8'):
        r = json.loads(line)
        if 'containerError' in r:
            container_errors[r['db']] = r['containerError']
            continue
        if r['db'] not in dbs_seen:
            dbs_seen.append(r['db'])
        probe[(r['type'], r['db'])].append(r)

types = []
seen = []
for (t, _db) in list(wb.keys()):
    if t not in seen:
        seen.append(t)
types = seen

def cell(t, db):
    recs = probe.get((t, db), [])
    if not recs:
        return ('no-probe', None)
    if all(r.get('notProbed') for r in recs):
        return ('not-probed', None)
    acc = [r for r in recs if r.get('accepted')]
    if acc:
        return ('accepted', acc)
    return ('rejected', recs)

rows_md = []
csv_rows = [['semantic_type', 'database', 'live_result', 'accepted_declarations', 'provider_type_reported',
             'clr_type_reported', 'workbook_status', 'workbook_spelling', 'disagreement']]
disagree = collections.Counter()
for t in types:
    for db in dbs_seen:
        status, acc = cell(t, db)
        wstat, wspell = wb.get((t, db), ('', ''))
        ok = status == 'accepted'
        decls = [r['decl'] for r in acc if r.get('accepted')] if ok else []
        ptype = acc[0].get('providerType', '') if ok else ''
        clr = acc[0].get('clrType', '') if ok else ''
        dis = ''
        if status == 'accepted' and wstat in ('X',):
            dis = 'probe accepts, workbook says X'
        elif status == 'rejected' and wstat == 'N':
            dis = 'workbook says N, no candidate accepted'
        elif status == 'accepted' and wstat == '?':
            dis = 'workbook unverified, probe resolves'
        if dis:
            disagree[dis] += 1
        csv_rows.append([t, db, status, ' ; '.join(decls), ptype, clr, wstat, wspell, dis])

def q(v):
    return '"' + str(v).replace('"', '""') + '"'

with open(os.path.join(S, 'crossref.csv'), 'w', encoding='utf-8') as f:
    for r in csv_rows:
        f.write(','.join(q(x) for x in r) + '\n')

# Markdown: one table per database summary + per-type first accepted declaration
summary = collections.Counter()
for t in types:
    for db in dbs_seen:
        summary[cell(t, db)[0]] += 1

with open(os.path.join(S, 'crossref.md'), 'w', encoding='utf-8') as f:
    f.write('# Live datatype cross-reference\n\n')
    f.write('Generated by summarize.py from datatype-probe results. A rejected candidate list means the\n')
    f.write('candidates tried were all refused; it is not proof the engine lacks the type.\n\n')
    f.write('Databases probed: ' + ', '.join(dbs_seen) + '\n\n')
    if container_errors:
        f.write('Container failures: ' + json.dumps(container_errors) + '\n\n')
    f.write('Cells: %s\n\n' % dict(summary))
    f.write('Disagreements with the workbook: %s\n\n' % dict(disagree))
    f.write('| semantic type | ' + ' | '.join(dbs_seen) + ' |\n')
    f.write('|---|' + '---|' * len(dbs_seen) + '\n')
    for t in types:
        cells = []
        for db in dbs_seen:
            status, acc = cell(t, db)
            if status == 'accepted':
                cells.append(acc[0]['decl'])
            elif status == 'rejected':
                cells.append('—')
            elif status == 'not-probed':
                cells.append('n/p')
            else:
                cells.append('?')
        f.write('| ' + t + ' | ' + ' | '.join(c.replace('|', '\\|') for c in cells) + ' |\n')

print('wrote', os.path.join(S, 'crossref.md'), 'and crossref.csv')
print('cells', dict(summary))
print('disagreements', dict(disagree))
print('dbs', dbs_seen, 'container errors', container_errors)
