#!/usr/bin/env python3
"""Writes docs/type-representation-matrix.md: every fidelity type on every database, with the CLR type, the DbType the
cell declares, the column type each database stores it in (or why it can't), and the library's documented decisions.

Inputs are the generator's own tables (gen_fidelity.py) and the live matrix (fidelity-matrix/*.tsv), so the document
cannot drift from what the tests run. Usage: gen_representation_doc.py <repo root>
"""
import glob
import importlib.util
import os
import sys

root = sys.argv[1]
probe = os.path.join(root, "tools", "datatype-probe")
spec = importlib.util.spec_from_file_location("gen_fidelity", os.path.join(probe, "gen_fidelity.py"))
sys.argv = [sys.argv[0], "/tmp"]  # gen_fidelity reads its output directory from argv; nothing is written
gf = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gf)

accepted, _refused = gf.probe_results()

# Each TSV lists its rows in SPEC order, so a cell is matched by position. Two rows can share a label (TimeOnly and
# TimeSpan are both "time without zone"), so a label alone would collapse them. The label check guards the order.
status = {}
for path in glob.glob(os.path.join(probe, "fidelity-matrix", "*.tsv")):
    db = os.path.basename(path)[:-len(".tsv")]
    lines = [line.rstrip("\n").split("\t") for line in open(path, encoding="utf-8") if line.strip()]
    assert len(lines) == len(gf.SPEC), (db, len(lines))
    for index, parts in enumerate(lines):
        assert parts[1] == gf.SPEC[index][1], (db, index, parts[1])
        if len(parts) >= 4:
            status[(db, index)] = parts[3]

SHORT = {
    "PostgreSql": "PostgreSQL", "SqlServer": "SQL Server", "Oracle": "Oracle", "Firebird": "Firebird",
    "CockroachDb": "CockroachDB", "MariaDb": "MariaDB", "MySql": "MySQL", "Sqlite": "SQLite", "DuckDB": "DuckDB",
    "YugabyteDb": "YugabyteDB", "TiDb": "TiDB", "SingleStore": "SingleStore", "SybaseASE": "Sybase ASE",
    "Spanner": "Spanner", "FlatFile": "FlatFile",
}


def esc(text):
    return text.replace("|", "\\|")


VERDICTS = ("by design: ", "server: ", "upstream: ")


def open_reason(db, sem):
    """The reason a refused cell is still open work, or None when its refusal is a settled verdict."""
    reason = gf.DB_REFUSED.get((db, sem))
    if reason is None or reason.startswith(VERDICTS):
        return None
    return reason


def cell(db, index):
    sem = gf.SPEC[index][1]
    st = status.get((db, index), "")
    if st.startswith("PASS"):
        declared = gf.resolve(accepted, db, sem)
        return "`" + esc(declared[0]) + "`" if declared else "`?`"
    if st.startswith("UNSUPPORTED"):
        reason = gf.DB_REFUSED.get((db, sem))
        if reason and open_reason(db, sem):
            return "**open**"
        if reason and reason.startswith("by design: "):
            return "design"
        if reason and reason.startswith("upstream: "):
            return "upstream"
        if reason and reason.startswith("server: "):
            return "server"
        return "—"
    return "FAIL" if st else "not run"


rows = []
for index, (_column, sem, clr, dbtype, _sample, _kind) in enumerate(gf.SPEC):
    rows.append((sem, clr, dbtype, [cell(db, index) for db in gf.DB_ENUM]))

out = []
out.append("# Type representation matrix")
out.append("")
out.append("Generated by `tools/datatype-probe/gen_representation_doc.py` from the live fidelity matrix and the generator's")
out.append("tables. Do not edit by hand: change the generator and re-run it.")
out.append("")
out.append("Each row is a type the library reads and writes. The **CLR type** is the property type, and the **DbType** is the")
out.append("type the cell's parameter is declared with. Each database column is the native column type that holds the value")
out.append("when the database has one, as the live integration matrix created it and read it back (a value that didn't")
out.append("round-trip is not shown as PASS). A cell is `—` when the server refused every spelling the probe tried for it;")
out.append("that is not proof the database lacks the type, only that none of the candidate spellings was accepted. **open**")
out.append("marks a cell where the probe found a type the database accepts and the library refuses it for a stated reason.")
out.append("The **open** cells are the work that remains; a `—` cell becomes work if a spelling the probe missed turns out to work.")
out.append("")
out.append("## Status")
out.append("")
passed = sum(1 for v in status.values() if v.startswith("PASS"))
unsupported = sum(1 for v in status.values() if v.startswith("UNSUPPORTED"))
opened = sum(1 for (db, index) in status
             if status[(db, index)].startswith("UNSUPPORTED") and open_reason(db, gf.SPEC[index][1]))
failed = sum(1 for v in status.values() if v.startswith("FAIL"))
verdicts = {"open": 0, "by design": 0, "server": 0, "upstream": 0}
for (db, index), value in status.items():
    if not value.startswith("UNSUPPORTED"):
        continue
    sem = gf.SPEC[index][1]
    reason = gf.DB_REFUSED.get((db, sem))
    if reason is None:
        continue
    if open_reason(db, sem):
        verdicts["open"] += 1
    elif reason.startswith("by design: "):
        verdicts["by design"] += 1
    elif reason.startswith("upstream: "):
        verdicts["upstream"] += 1
    else:
        verdicts["server"] += 1
dashes = unsupported - sum(verdicts.values())
out.append(f"- {len(rows)} types, {len(gf.DB_ENUM)} databases, {len(rows) * len(gf.DB_ENUM)} cells.")
out.append(f"- {passed} cells store and read the value back.")
out.append(f"- {verdicts['open']} open: the database has a type and the library does not handle it yet.")
out.append(f"- {verdicts['by design']} unsupported by design: a stated decision (reason in the table below).")
out.append(f"- {verdicts['server']} unsupported by server: the database lacks a working feature for the value.")
out.append(f"- {verdicts['upstream']} upstream defect: the database's own bug, reproduced live.")
out.append(f"- {dashes} with no column type on that database (`—`): no candidate spelling was accepted.")
out.append(f"- {failed} cells fail.")
out.append("")
out.append("## Types by database")
out.append("")
header = "| Type | CLR type | DbType | " + " | ".join(SHORT[db] for db in gf.DB_ENUM) + " |"
out.append(header)
out.append("|" + "---|" * (3 + len(gf.DB_ENUM)))
for sem, clr, dbtype, cells in rows:
    out.append(f"| {esc(sem)} | `{esc(clr)}` | {dbtype} | " + " | ".join(cells) + " |")
out.append("")
out.append("## Cells that can't be represented")
out.append("")
out.append("Every refused cell and the verdict it has: **open** (work remaining), unsupported by design (a decision, reason given),")
out.append("unsupported by server (the database lacks a working feature), or upstream defect (the database's own bug, reproduced live).")
out.append("a database that has the type can be supported. The `—` cells are not listed: the probe found no accepted spelling.")
out.append("")
out.append("| Database | Type | Status | Current reason |")
out.append("|---|---|---|---|")
for db in gf.DB_ENUM:
    for sem, _clr, _dbtype, _cells in rows:
        reason = gf.DB_REFUSED.get((db, sem))  # a label shared by two rows has no refusal of its own
        if reason:
            if open_reason(db, sem):
                label = "**open**"
            elif reason.startswith("by design: "):
                label = "unsupported by design"
            elif reason.startswith("upstream: "):
                label = "upstream defect"
            else:
                label = "unsupported by server"
            out.append(f"| {SHORT[db]} | {esc(sem)} | {label} | {esc(reason)} |")
out.append("")

path = os.path.join(root, "docs", "type-representation-matrix.md")
with open(path, "w", encoding="utf-8") as f:
    f.write("\n".join(out))
print("wrote", path, len(rows), "types")
